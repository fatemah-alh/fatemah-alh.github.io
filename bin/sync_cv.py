#!/usr/bin/env python3
"""Copy the authoritative RenderCV document into Jekyll's data directory.

Run after editing the source YAML. No schema conversion is performed.
"""

import argparse
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Fatemah_Alhamdoosh_RenderCV_v6.yaml"
TARGET = ROOT / "_data/cv.yml"
BIBLIOGRAPHY = ROOT / "_bibliography/papers.bib"
DOWNLOAD = ROOT / "assets/bibliography/papers.bib"


def bibliography(cv):
    """Generate the two source-verified records, retaining their publication status."""
    records = ["% Generated by bin/sync_cv.py from the authoritative RenderCV YAML.\n"]
    for paper in cv["sections"]["Selected Publications"]:
        authors = " and ".join(author.strip("*") for author in paper["authors"])
        fields = {"title": paper["title"], "author": authors, "year": paper["date"],
                  "selected": "true"}
        if paper.get("doi") == "10.1109/TBIOM.2025.3592836":
            kind, key = "article", "alhamdoosh2025pain"
            venue = re.fullmatch(r"(.+), (\d+), (\d+)–(\d+)", paper["journal"])
            assert venue, "Review updated journal metadata before regenerating BibTeX"
            fields.update(journal=venue[1], volume=venue[2], pages=f"{venue[3]}--{venue[4]}", doi=paper["doi"])
        elif paper.get("url") == "https://arxiv.org/abs/2607.03934":
            kind, key = "misc", "alhamdoosh2026egoinertia"
            fields.update(note="arXiv preprint", eprint="2607.03934", archivePrefix="arXiv",
                          arxiv="2607.03934", url=paper["url"])
        else:
            raise ValueError("Verify new publication metadata and extend the bibliography mapping")
        records.append("@" + kind + "{" + key + ",\n" +
                       "".join(f"  {name} = {{{value}}},\n" for name, value in fields.items()) + "}\n")
    return "\n".join(records)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated data is stale")
    args = parser.parse_args()
    source = SOURCE.read_text()
    document = yaml.safe_load(source)
    assert document["cv"]["name"] == "Fatemah Alhamdoosh"
    assert isinstance(document["cv"]["sections"], dict)
    if args.check:
        assert yaml.safe_load(TARGET.read_text()) == document, "Run python bin/sync_cv.py"
        assert BIBLIOGRAPHY.read_text() == bibliography(document["cv"]), "Regenerate the bibliography"
        assert DOWNLOAD.read_text() == BIBLIOGRAPHY.read_text(), "Regenerate the BibTeX download"
        print("CV data and bibliography match the authoritative RenderCV YAML.")
    else:
        TARGET.write_text("# Generated by bin/sync_cv.py; edit the root RenderCV YAML instead.\n" + source)
        BIBLIOGRAPHY.write_text(bibliography(document["cv"]))
        DOWNLOAD.parent.mkdir(parents=True, exist_ok=True)
        DOWNLOAD.write_text(BIBLIOGRAPHY.read_text())
        print("Updated _data/cv.yml and the verified bibliography.")


if __name__ == "__main__":
    main()
